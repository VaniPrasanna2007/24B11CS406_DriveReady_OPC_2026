@tool
def lookup_price(item: str, qty: int = 1) -> str:
    """Get the total price in rupees for a quantity of an item in CodeCraft Studio's catalogue.

    Args:
        item: Catalogue item such as "starter kit", "prompt pack", or "1-on-1 review"
        qty: Number of units requested
    """
    key = item.lower().strip()
    if key not in CATALOGUE:
        return f"'{item}' is not in our catalogue. Available items: {', '.join(CATALOGUE)}."
    if qty < 1:
        return "Quantity must be at least 1."
    return f"{qty} x {key} = Rs {CATALOGUE[key]['price'] * qty}"

@tool
def check_availability(item: str) -> str:
    """Check whether an item or session in CodeCraft Studio's catalogue is currently available."""
    key = item.lower().strip()
    if key not in CATALOGUE:
        return f"'{item}' is not in our catalogue. Available items: {', '.join(CATALOGUE)}."
    status = "available" if CATALOGUE[key]["available"] else "currently unavailable"
    return f"'{key}' is {status}."

